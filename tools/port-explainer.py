#!/usr/bin/env python3
"""Port a standalone explainer site into the Understanding Nature library.

    tools/port-explainer.py <name> <source site dir> <theme> [--css-marker "<comment>"]

Re-runnable: it overwrites site/<name>/js, index.html and css/<name>.css from the source,
so an explainer still being developed in its original project can be re-synced.

What it does
  · copies the source tree (minus the files the kit now provides)
  · rewires `./util.js` imports to the shared kit
  · regenerates main.js on top of kit/chapters.js + kit/library.js
  · keeps only explainer-specific CSS (everything after --css-marker, plus .card.a/.b)
  · links kit.css, sets <body data-theme data-explainer data-root>
"""
import re, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {'css/style.css', 'js/util.js', '_mobile.html'}


def main():
    args = sys.argv[1:]
    marker = None
    if '--css-marker' in args:
        i = args.index('--css-marker'); marker = args[i + 1]; del args[i:i + 2]
    name, src, theme = args
    src = Path(src).resolve()
    dest = ROOT / 'site' / name
    if (dest / 'js').exists():
        shutil.rmtree(dest / 'js')
    for f in src.rglob('*'):
        rel = f.relative_to(src).as_posix()
        if f.is_dir() or rel in SKIP:
            continue
        out = dest / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(f, out)

    # JS: shared helpers come from the kit
    for js in (dest / 'js').glob('*.js'):
        s = js.read_text()
        s = s.replace("from './util.js'", "from '../../kit/util.js'").replace('from "./util.js"', "from '../../kit/util.js'")
        js.write_text(s)

    # main.js → kit-based loader (keeps the source's chapter list)
    main_js = dest / 'js' / 'main.js'
    m = re.search(r'const chapters = \[(.*?)\];', main_js.read_text(), re.S)
    if m:
        main_js.write_text(
            "// Generated by tools/port-explainer.py: chapter list from the source project,\n"
            "// loader + library chrome from the shared kit.\n"
            "import { bootChapters } from '../../kit/chapters.js';\n"
            "import { initLibrary } from '../../kit/library.js';\n\n"
            "initLibrary();\n"
            f"bootChapters((f) => import(`./${{f}}`), [{m.group(1)}]);\n")

    # CSS: only what's specific to this explainer
    css = (src / 'css' / 'style.css').read_text()
    own = []
    own += [l for l in css.splitlines() if re.match(r'\s*\.card\.(a|b)\b', l)]
    # single-line rules aimed at this explainer's own element ids stay with the explainer
    own += [l for l in (css[:css.index(marker)] if marker and marker in css else css).splitlines() if re.match(r'#[\w-]+[^{]*\{.*\}\s*$', l)]
    if marker and marker in css:
        own.append(css[css.index(marker):])
    (dest / 'css').mkdir(exist_ok=True)
    (dest / 'css' / f'{name}.css').write_text(
        f"/* {name}: explainer-specific styles (shared styles live in kit/kit.css) */\n" + '\n'.join(own) + '\n')

    # HTML: kit stylesheet + library attributes
    html_p = dest / 'index.html'
    h = html_p.read_text()
    h = h.replace('<link rel="stylesheet" href="css/style.css">',
                  f'<link rel="stylesheet" href="../kit/kit.css">\n<link rel="stylesheet" href="css/{name}.css">')
    h = re.sub(r'<body[^>]*>', f'<body data-theme="{theme}" data-explainer="{name}" data-root="../">', h, count=1)
    if 'og:image' not in h:
        url = f'https://mklasen.github.io/understanding-nature/{name}/'
        title = re.search(r'<title>(.*?)</title>', h, re.S).group(1).strip()
        desc_m = re.search(r'<meta name="description" content="(.*?)">', h)
        desc = desc_m.group(1) if desc_m else ''
        meta = (f'<link rel="canonical" href="{url}">\n'
                '<meta property="og:type" content="website">\n'
                '<meta property="og:site_name" content="Understanding Nature">\n'
                f'<meta property="og:title" content="{title}">\n'
                f'<meta property="og:description" content="{desc}">\n'
                f'<meta property="og:url" content="{url}">\n'
                f'<meta property="og:image" content="{url}og.jpg">\n'
                '<meta property="og:image:width" content="1200">\n<meta property="og:image:height" content="630">\n'
                '<meta name="twitter:card" content="summary_large_image">\n'
                f'<meta name="twitter:image" content="{url}og.jpg">\n')
        h = h.replace('<link rel="stylesheet" href="../kit/kit.css">', meta + '<link rel="stylesheet" href="../kit/kit.css">', 1)
    html_p.write_text(h)
    print(f'ported {src} → {dest}')


if __name__ == '__main__':
    main()
